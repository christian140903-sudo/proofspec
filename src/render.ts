import { mkdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { ClaimResult, ClaimStatus, ProofspecReport, ReportFormat } from './types.js';

const STATUS_ICON: Record<ClaimStatus, string> = {
  verified: '✓', failed: '✕', unknown: '?', unsupported: '∅', blocked: '⊘',
};

export function renderReport(report: ProofspecReport, format: ReportFormat): string {
  switch (format) {
    case 'json': return `${JSON.stringify(report, null, 2)}\n`;
    case 'markdown': return renderMarkdown(report);
    case 'html': return renderHtml(report);
    case 'mermaid': return renderMermaid(report);
    case 'sarif': return renderSarif(report);
  }
}

export async function writeReports(report: ProofspecReport, outputDir: string, formats: ReportFormat[] = ['json', 'markdown', 'html', 'mermaid', 'sarif']): Promise<string[]> {
  await mkdir(outputDir, { recursive: true });
  const extension: Record<ReportFormat, string> = { json: 'json', markdown: 'md', html: 'html', mermaid: 'mmd', sarif: 'sarif' };
  const paths: string[] = [];
  for (const format of [...new Set(formats)]) {
    const path = join(outputDir, `proofspec-report.${extension[format]}`);
    await writeFile(path, renderReport(report, format), 'utf8');
    paths.push(path);
  }
  return paths;
}

export function renderMarkdown(report: ProofspecReport): string {
  const lines = [
    `# Proofspec report — ${report.project.name}`,
    '',
    `Generated: ${report.generatedAt}`,
    `Gate: **${report.summary.gatePassed ? 'PASS' : 'FAIL'}**`,
    `Ledger: **${report.ledger.valid ? 'valid' : 'invalid'}** (${report.ledger.receiptsChecked} receipts checked)`,
    `Report digest: \`${report.reportDigest}\``,
    '',
    '| Status | Claim | Severity | Evidence | Dependencies |',
    '|---|---|---|---:|---|',
    ...report.claims.map((claim) => `| ${STATUS_ICON[claim.effectiveStatus]} ${claim.effectiveStatus} | ${escapeMarkdown(claim.statement)} | ${claim.severity} | ${claim.evidence.length} | ${claim.dependsOn.join(', ') || '—'} |`),
    '',
  ];
  for (const claim of report.claims) lines.push(...claimMarkdown(claim));
  lines.push('---', '', 'Generated by [Proofspec](https://github.com/christian140903-sudo/proofspec). A satisfied verifier proves only its configured observation.', '');
  return `${lines.join('\n')}\n`;
}

export function renderMermaid(report: ProofspecReport): string {
  const lines = ['flowchart LR'];
  for (const claim of report.claims) {
    lines.push(`  ${nodeId(claim.id)}["${escapeMermaid(`${STATUS_ICON[claim.effectiveStatus]} ${claim.id}: ${claim.statement}`)}"]`);
  }
  for (const claim of report.claims) {
    for (const dependency of claim.dependsOn) lines.push(`  ${nodeId(dependency)} --> ${nodeId(claim.id)}`);
  }
  for (const claim of report.claims) lines.push(`  class ${nodeId(claim.id)} ${claim.effectiveStatus}`);
  lines.push(
    '  classDef verified fill:#123b2d,stroke:#53e6a7,color:#effff8',
    '  classDef failed fill:#401c22,stroke:#ff8f96,color:#fff1f2',
    '  classDef unknown fill:#3b3019,stroke:#ffc66d,color:#fff8e8',
    '  classDef unsupported fill:#242936,stroke:#8e9aaf,color:#f0f3f8',
    '  classDef blocked fill:#2d2341,stroke:#a879ff,color:#f6f0ff',
  );
  return `${lines.join('\n')}\n`;
}

export function renderSarif(report: ProofspecReport): string {
  const failing = report.claims.filter((claim) => claim.effectiveStatus !== 'verified');
  const sarif = {
    version: '2.1.0',
    $schema: 'https://json.schemastore.org/sarif-2.1.0.json',
    runs: [{
      tool: {
        driver: {
          name: 'Proofspec',
          informationUri: 'https://github.com/christian140903-sudo/proofspec',
          version: '0.1.0',
          rules: failing.map((claim) => ({
            id: `proofspec/${claim.id}`,
            shortDescription: { text: claim.statement },
            helpUri: 'https://github.com/christian140903-sudo/proofspec/blob/main/docs/CONFIG.md',
          })),
        },
      },
      results: failing.map((claim) => ({
        ruleId: `proofspec/${claim.id}`,
        level: claim.severity === 'error' ? 'error' : claim.severity === 'warning' ? 'warning' : 'note',
        message: { text: `${claim.effectiveStatus}: ${claim.statement}${claim.blockedBy.length ? `; blocked by ${claim.blockedBy.join(', ')}` : ''}` },
        locations: [{ physicalLocation: { artifactLocation: { uri: report.configFile }, region: { startLine: 1 } } }],
      })),
    }],
  };
  return `${JSON.stringify(sarif, null, 2)}\n`;
}

