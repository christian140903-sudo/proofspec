function claimMarkdown(claim: ClaimResult): string[] {
  const lines = [
    `## ${STATUS_ICON[claim.effectiveStatus]} ${claim.id}`,
    '',
    claim.statement,
    '',
    `- Direct status: \`${claim.directStatus}\``,
    `- Effective status: \`${claim.effectiveStatus}\``,
    `- Severity: \`${claim.severity}\``,
    `- Policy: \`${claim.policy.mode}${claim.policy.mode === 'at_least' ? `:${claim.policy.count}` : ''}\``,
  ];
  if (claim.blockedBy.length) lines.push(`- Blocked by: ${claim.blockedBy.map((item) => `\`${item}\``).join(', ')}`);
  lines.push('', '### Evidence', '');
  if (!claim.evidence.length) lines.push('- No evidence configured.');
  for (const item of claim.evidence) {
    lines.push(`- **${item.id}** — \`${item.verdict}\` / \`${item.evidenceClass}\`: ${item.summary}  `, `  Receipt: \`${item.receiptHash}\``);
  }
  if (claim.limitations.length) lines.push('', '### Limitations', '', ...claim.limitations.map((item) => `- ${item}`));
  lines.push('');
  return lines;
}

function escapeMarkdown(value: string): string { return value.replaceAll('|', '\\|').replaceAll('\n', ' '); }
function escapeMermaid(value: string): string { return value.replaceAll('"', "'").replaceAll('\n', ' '); }
function nodeId(value: string): string { return `claim_${value.replace(/[^a-zA-Z0-9_]/g, '_')}`; }
function escapeHtml(value: string): string { return value.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&#39;'); }
